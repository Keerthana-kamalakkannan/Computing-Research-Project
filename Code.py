def clean_topic_text(text):

    text = str(text).lower()

    # URLs
    text = re.sub(
        r"https?://\S+|www\.\S+",
        " ",
        text
    )

    # Markdown links
    text = re.sub(
        r"\[([^\]]+)\]\([^)]+\)",
        r"\1",
        text
    )

    # Usernames
    text = re.sub(
        r"/u/\w+|u/\w+|@\w+",
        " ",
        text
    )

    # Subreddits
    text = re.sub(
        r"/r/\w+|r/\w+",
        " ",
        text
    )

    # HTML entities
    text = re.sub(
        r"&\w+;",
        " ",
        text
    )

    # Keep alphabetic characters
    text = re.sub(
        r"[^a-z\s]",
        " ",
        text
    )

    # Whitespace
    text = re.sub(
        r"\s+",
        " ",
        text
    ).strip()

    words = [
        word
        for word in text.split()
        if word not in ALL_STOPWORDS
        and len(word) >= 3
    ]

    return " ".join(words)


