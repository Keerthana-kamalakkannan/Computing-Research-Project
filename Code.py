print("✓ BERT loaded")


def convert_bert_label(label):

    label = str(label).lower()

    if "1" in label or "2" in label:

        return "Negative"

    elif "3" in label:

        return "Neutral"

    elif "4" in label or "5" in label:

        return "Positive"

    return "Neutral"


def run_sentiment_model(
    model_pipeline,
    texts,
    batch_size=16
):

    results = []

    for start in range(
        0,
        len(texts),
        batch_size
    ):

        batch = texts[
            start:start + batch_size
        ]

        try:

            batch_results = model_pipeline(
                batch,
                batch_size=batch_size
            )

            results.extend(
                batch_results
            )

        except Exception as e:

            print(
                "Batch fallback:",
                str(e)[:100]
            )

            for text in batch:

                try:

                    result = model_pipeline(
                        text[:2000]
                    )[0]

                    results.append(
                        result
                    )

                except Exception:

                    results.append({
                        "label": "3 stars",
                        "score": 0.0
                    })

        processed = min(
            start + batch_size,
            len(texts)
        )

        if (
            start == 0
            or processed % 100 == 0
        ):

            print(
                f"Processed "
                f"{processed}/{len(texts)}"
            )

    return results


