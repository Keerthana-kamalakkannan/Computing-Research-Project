# BERT-based sentiment model.
#
# IMPORTANT:
# This is a BERT-base architecture fine-tuned for sentiment,
# rather than a generic un-fine-tuned BERT model.
#
# It produces 5-star sentiment, which we convert to:
# Negative / Neutral / Positive.

BERT_MODEL = (
    "nlptown/"
    "bert-base-multilingual-uncased-sentiment"
)

